/**
 * Regenerates docs/rules.md from the rule metadata, so the docs never drift from the code.
 * Run with `pnpm docs:rules`; CI fails if the committed file is out of date.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DEPENDENCY_RULE } from '../src/dependencies/audit.ts';
import { builtinRules } from '../src/rules/index.ts';
import type { RuleMeta } from '../src/types.ts';

const CATEGORY_TITLES: Record<RuleMeta['category'], string> = {
  xss: 'XSS',
  secrets: 'Secrets',
  auth: 'Auth',
  misconfig: 'Misconfiguration',
  dependencies: 'Dependencies',
};

const metas = [...builtinRules.map((rule) => rule.meta), DEPENDENCY_RULE];

const lines = [
  '# Rules',
  '',
  '<!-- Generated by scripts/generate-rules-doc.ts. Do not edit by hand. -->',
  '',
  'Every rule can be configured by id or name in `rules` (`off`, `warn` or `error`) and suppressed inline with',
  '`// frontguard-ignore-next-line <id>`.',
  '',
  '| ID | Name | Severity | Title |',
  '| --- | --- | --- | --- |',
  ...metas.map(
    (m) => `| [${m.id}](#${m.id.toLowerCase()}) | \`${m.name}\` | ${m.severity} | ${m.title} |`,
  ),
  '',
];

for (const category of Object.keys(CATEGORY_TITLES) as RuleMeta['category'][]) {
  lines.push(`## ${CATEGORY_TITLES[category]}`, '');
  for (const m of metas.filter((meta) => meta.category === category)) {
    const refs = [m.cwe, m.owasp].filter(Boolean).join(' · ');
    lines.push(
      `### ${m.id}`,
      '',
      `**${m.title}** · \`${m.name}\` · default severity: **${m.severity}**${refs ? ` · ${refs}` : ''}`,
      '',
      m.description,
      '',
      `**How to fix:** ${m.remediation}`,
      '',
    );
  }
}

const docsDir = join(import.meta.dirname, '..', 'docs');
mkdirSync(docsDir, { recursive: true });
writeFileSync(join(docsDir, 'rules.md'), lines.join('\n'));
console.log(`docs/rules.md: ${metas.length} rules`);
